_BY_ID = {item['feature_id']: item for item in _FEATURES}


def features():
    """Return independent records suitable for authenticated capability UIs."""
    return deepcopy(list(_FEATURES))


def get_feature(feature_id):
    """Look up an exact reviewed identifier; unknown identifiers return None."""
    return deepcopy(_BY_ID.get(feature_id)) if isinstance(feature_id, str) else None


def model_features(is_admin: bool, approved: bool, permissions=(), bot_capabilities=None):
    from types import SimpleNamespace
    from .bot_policy import feature_enabled
    """Filter discovery only; callers must still enforce fresh business rights.

    Event features are discoverable by approved members. Their individual event
    permissions and state are intentionally not inferred from these two flags.
    """
    from .ai_permissions import feature_permission
    capabilities=set(permissions)
    levels = {'public'}
    if approved is True or is_admin is True:
        levels.update(('member', 'event'))
    if is_admin is True:
        levels.add('admin')
    ctx = SimpleNamespace(capabilities=bot_capabilities)
    return [deepcopy(item) for item in _FEATURES if feature_enabled(ctx, item) and
            (item['permission'] in levels or approved and feature_permission(item) in capabilities)]


