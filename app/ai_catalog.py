def local_route(text):
    """Return a likely catalogue ID, without checking/granting permission.

    Only high-confidence onboarding, help and management phrases are handled.
    Ordinary parameterised business requests fall through to structured intent
    interpretation. A result is a destination, never authorisation to execute.
    """
    if not isinstance(text, str) or not text.strip() or len(text) > 4000:
        return None
    # Private forms stay local, including a compound request containing a secret.
    # Ordinary business clauses must reach the semantic planner as a whole;
    # selecting the first matching navigation rule would silently discard work.
    from .ai import unsupported_reason
    compound = bool(re.search(r'然后|并且|之后|再(?:帮|把|查|看|给|将|报|取消|改|设|组织)|同时|接着|顺便|以及|[；;]', text))
    if not compound:
        # A comma/newline can join full requests without a conjunction. Detect
        # additional business clauses only to avoid short-circuiting the model;
        # do not parse their parameters or infer operations here. Incidental
        # context ("管理员导入过我，怎么关联手机号") remains one local route.
        clauses = [part.strip() for part in re.split(r'[，,\r\n]+', text) if part.strip()]
        actions = r'报名|取消|名单|统计|查询|查看|自评|组织|对战|比分|积分赛|五人转|五羽伦比|(?:开启|关闭)\s*AI'
        if len(clauses) > 1:
            compound = sum(bool(re.search(actions, part, re.I) or any(
                re.search(pattern, part, re.I) for _, pattern in _LOCAL_RULES)) for part in clauses) > 1
    sensitive = unsupported_reason(text)
    for feature_id, pattern in _LOCAL_RULES:
        if re.search(pattern, text, re.I):
            if not sensitive and compound:
                return None
            if not sensitive and feature_id in {'membership.renewal','registration.constraints','venue.reminders','venue.slots'}:
                if re.search(r'[0-9一二三四五六七八九十]|开启|关闭|不限|解除', text) and not re.search(r'如何|怎么|哪里|入口|帮助|说明', text):
                    return None
            if not sensitive and feature_id=='membership.review' and re.search(r'通过|同意|批准|拒绝|退回',text) and not re.search(r'如何|怎么|哪里|入口|帮助|说明|状态|进度|了吗',text):
                return None
            return feature_id
    return None
